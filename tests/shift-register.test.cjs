const assert=require('node:assert/strict');
const {parseRows:parseSourceRows,registeredTime}=require('../scripts/shift-register.cjs');
const sourceMeta={fileId:'test-file',sheetId:'test-sheet',url:'https://docs.google.com/spreadsheets/d/test-file/edit',timezone:'Atlantic/Canary'};
const parseRows=(rows,drivers,vehicles,firstRow=2)=>parseSourceRows(rows,drivers,vehicles,firstRow,sourceMeta);
const drivers=[{id:'a',full_name:'Álvaro Teste'},{id:'b',full_name:'Nome Repetido'},{id:'c',full_name:'Nome Repetido'}];
const vehicles=[{id:'v',plate:'AA-00-AA'}];
const source=[['2026/11/10 11:50:15','SAIDA TURNO','ALVARO TESTE','AA00AA','1']];
const [row]=parseRows(source,drivers,vehicles,100);
assert.equal(row.source_row,100);
assert.equal(row.driver_id,'a');
assert.equal(row.vehicle_id,'v');
assert.equal(row.registered_at,'2026-11-10T11:50:15.000Z');
assert.equal(row.event_kind,'exit');
assert.ok(!('odometer_km' in row));
assert.ok(!('odometer_text' in row));
assert.equal(parseRows(source,drivers,vehicles,100)[0].source_hash,row.source_hash,'Idempotent source fingerprint');
assert.equal(parseRows([['2026/11/10 11:50:15','SAIDA TURNO','ALVARO TESTE','AA00AA','2']],drivers,vehicles,100)[0].source_hash,row.source_hash,'Odometer edits have no effect');
assert.notEqual(parseRows([['2026/11/10 11:50:16','SAIDA TURNO','ALVARO TESTE','AA00AA']],drivers,vehicles,100)[0].source_hash,row.source_hash,'Relevant source edits remain detectable');
const flags=[];
assert.equal(registeredTime('2026/07/10 12:00:00',flags),'2026-07-10T11:00:00.000Z');
assert.equal(registeredTime('2026/10/25 01:30:00',flags),null);
assert.ok(flags.includes('ambiguous_timestamp'));
assert.equal(registeredTime('2026/02/31 12:00:00',flags),null);
const [ambiguous]=parseRows([['invalid','OTHER','Nome Repetido','XX-00-XX','abc']],drivers,vehicles);
assert.equal(ambiguous.driver_id,null);
assert.equal(ambiguous.vehicle_id,null);
assert.ok(ambiguous.review_flags.includes('ambiguous_driver'));
assert.ok(ambiguous.review_flags.includes('unmatched_vehicle'));
assert.ok(ambiguous.review_flags.includes('invalid_timestamp'));
console.log('PASS shift provenance, idempotence, timestamp/DST ambiguity, exact unique identity matching and review flags');
